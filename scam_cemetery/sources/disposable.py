"""Disposable-inbox domains from a vendored snapshot.

The file is the normal-mode list published by
https://github.com/disposable/disposable-email-domains and generated by
https://github.com/disposable/disposable. It is not the strict list, so
ordinary freemail providers are not treated as disposable. A hit is
suspicious, which cannot be a GO.
"""

from importlib.resources import files

import httpx

from scam_cemetery.models import SourceResult
from scam_cemetery.subjects import parse_email

_DOMAINS: frozenset[str] | None = None


def disposable_domains() -> frozenset[str]:
    """Load the vendored list once. Lines are already lowercase domains."""
    global _DOMAINS
    if _DOMAINS is None:
        path = files("scam_cemetery").joinpath("data/disposable_domains.txt")
        text = path.read_text(encoding="utf-8")
        _DOMAINS = frozenset(
            line.strip().lower()
            for line in text.splitlines()
            if line.strip() and not line.startswith("#")
        )
    return _DOMAINS


def disposable_match(domain: str, domains: frozenset[str] | None = None) -> str | None:
    """Return the listed domain, walking from the full name up to its parent.

    ``a.mailinator.com`` matches ``mailinator.com``. A public suffix alone is
    never consulted, because the walk stops before the final label.
    """
    listed = disposable_domains() if domains is None else domains
    labels = [label for label in domain.lower().strip(".").split(".") if label]
    for start in range(len(labels) - 1):
        candidate = ".".join(labels[start:])
        if candidate in listed:
            return candidate
    return None


class DisposableDomainSource:
    name = "disposable_domain"
    display_name = "Disposable domain"

    def __init__(self, domains: frozenset[str] | None = None) -> None:
        self._domains = domains

    def is_configured(self) -> bool:
        return True

    async def lookup(self, target: str, client: httpx.AsyncClient) -> SourceResult:
        del client
        parsed = parse_email(target)
        if parsed is None:
            return SourceResult(
                source=self.name,
                display_name=self.display_name,
                status="suspicious",
                summary="Disposable domain: address syntax is not valid",
            )
        domain = parsed[1]
        matched = disposable_match(domain, self._domains)
        if matched is None:
            return SourceResult(
                source=self.name,
                display_name=self.display_name,
                status="clean",
                summary=f"Disposable domain: {domain} is not on the disposable list",
                detail={"domain": domain, "listed": False},
            )
        return SourceResult(
            source=self.name,
            display_name=self.display_name,
            status="suspicious",
            summary=f"Disposable domain: {domain} is on the disposable-inbox list ({matched})",
            detail={"domain": domain, "listed": True, "matched": matched},
        )
